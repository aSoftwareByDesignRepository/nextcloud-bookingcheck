namespace OCA\BookingCheck\BackgroundJob;

use OCA\BookingCheck\Service\AuditService;
use OCA\BookingCheck\Service\UpgradeBackupService;
use OCP\AppFramework\Utility\ITimeFactory;
use OCP\BackgroundJob\TimedJob;
use OCP\Lock\ILockingProvider;
use OCP\Lock\LockedException;
use Psr\Log\LoggerInterface;

/** Daily tamper check — a broken chain row id goes to the log + admin. */
class AuditChainVerifyJob extends TimedJob
{
	public function __construct(
		ITimeFactory $time,
		private readonly AuditService $audit,
		private readonly LoggerInterface $logger,
		private readonly ILockingProvider $locking,
	) {
		parent::__construct($time);
		$this->setInterval(86400);
	}

	protected function run($argument): void
	{
		// Shared lock on the upgrade-backup key: a restore holds it
		// exclusively (UpgradeBackupService::runExclusive) — app-table
		// scans/writes must not interleave with a mid-restore
		// truncate+reinsert. A skip is not a failure: TimedJobs re-run
		// on their interval.
		try {
			$this->locking->acquireLock(
				UpgradeBackupService::LOCK_KEY,
				ILockingProvider::LOCK_SHARED,
				'BookingCheck audit chain verify',
			);
		} catch (LockedException) {
			$this->logger->info('BookingCheck: skipping audit chain verify — upgrade backup/restore in progress');
			return;
		}
		try {
			$this->doRun($argument);
		} finally {
			$this->locking->releaseLock(UpgradeBackupService::LOCK_KEY, ILockingProvider::LOCK_SHARED);
		}
	}

	private function doRun($argument): void
	{
		$brokenAt = $this->audit->verifyChain();
		if ($brokenAt !== 0) {
			$this->logger->critical('BookingCheck audit chain broken at row ' . $brokenAt
				. ' — possible tampering. Investigate immediately.');
		}
	}
}
